#!/usr/bin/env python3
"""Unsupervised consistency check of the timing attribution (all 550 requests: 518 evaluation
requests + the 32 public-sample requests, which share the workflow's reporting groups).

The hidden answers are not available, but the attribution model makes a falsifiable prediction
that can be checked against events it did *not* use: every "Policy action completed" event on
a record that is linked to a case **by identifiers** should sit at a seconds-of-minute phase of

    primary_second + 40 s + 29.5 s * k      (slot k = 0, 1, 2, 3; tolerance 2 s)

where ``primary_second`` comes from the primary-profile submission that the timing attribution
chose for that case.  If the account attribution were wrong, the agreement would drop to the
chance level, which is measured by pairing each event with the primary submission of a
*different* case from the same reporting group (or a fixed shift when the group has one case).

It also reports how many identifier-free anonymisation / legal-hold events were attributed to
exactly one case.

Usage (from repository root):
    python3 code/evaluation/consistency.py      # writes code/evaluation/consistency.md
"""
from __future__ import annotations

import csv
import os
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
CODE = os.path.dirname(HERE)
REPO = os.path.dirname(CODE)
sys.path.insert(0, CODE)

from ghost_audit.attribution import case_phase, circular_distance, in_window  # noqa: E402
from ghost_audit.config import POLICY_ACTION_WINDOW_MIN, POLICY_SLOT_ADVANCE_S  # noqa: E402
from ghost_audit.context import ts  # noqa: E402
from ghost_audit.engine import Auditor  # noqa: E402

TOL = 2.0


def agrees(second: int, phase: int) -> bool:
    return any(circular_distance(second, (phase + 40 + POLICY_SLOT_ADVANCE_S * k) % 60) <= TOL for k in range(4))


def read(path):
    with open(path, encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def main():
    ds = os.path.join(REPO, "dataset")
    auditor = Auditor(ds, os.path.join(CODE, ".cache"))
    test = read(os.path.join(ds, "deletion_requests.csv"))
    sample = read(os.path.join(ds, "sample_deletion_requests.csv"))
    auditor.prepare(test + sample)
    data = auditor.data
    cases = [c for c in auditor.ctx.values() if c.auditable]
    groups = defaultdict(list)
    for c in cases:
        groups[c.req["reported_at"]].append(c)

    policy = [a for a in data.activities if "Policy action completed" in a["details"]]
    checked = agree = chance = 0
    for R, group in groups.items():
        Rt = ts(R)
        acts = [a for a in policy if in_window(a["_t"], Rt, POLICY_ACTION_WINDOW_MIN)]
        for i, c in enumerate(group):
            p = case_phase(data, c)
            if p is None:
                continue
            other = case_phase(data, group[(i + 1) % len(group)]) if len(group) > 1 else None
            if other is None or other == p:
                other = (p + 17) % 60
            for a in acts:
                if a["resource_id"] in c.direct:
                    checked += 1
                    agree += agrees(a["_t"].second, p)
                    chance += agrees(a["_t"].second, other)

    free_kinds = defaultdict(lambda: [0, 0])
    owners = defaultdict(set)
    for c in cases:
        for rid, why in c.attributed.items():
            if any(w.startswith(("policy-phase:", "policy-order:")) for w in why):
                owners[rid].add(c.case_id)
    for R, group in groups.items():
        Rt = ts(R)
        for a in policy:
            if a["event_type"] not in ("ANONYMIZE_RECORD", "RETAIN_RECORD") or not in_window(a["_t"], Rt, POLICY_ACTION_WINDOW_MIN):
                continue
            if any(a["resource_id"] in k.direct for k in auditor.ctx.values() if k.deletion):
                continue
            free_kinds[a["event_type"]][0] += 1
            free_kinds[a["event_type"]][1] += len(owners.get(a["resource_id"], ())) == 1

    lines = [
        "| check | result |",
        "|---|---|",
        f"| identifier-linked policy events whose phase matches the attributed primary submission | "
        f"**{agree}/{checked}** ({100 * agree / max(checked, 1):.1f} %) |",
        f"| same events against another case's submission (chance level) | {chance}/{checked} "
        f"({100 * chance / max(checked, 1):.1f} %) |",
    ]
    for kind, (n, one) in sorted(free_kinds.items()):
        lines.append(f"| identifier-free `{kind}` events attributed to exactly one case | {one}/{n} |")
    text = "# Unsupervised consistency of the timing attribution\n\nGenerated by `python3 code/evaluation/consistency.py`.\n\n" + "\n".join(lines) + "\n"
    with open(os.path.join(HERE, "consistency.md"), "w", encoding="utf-8") as fh:
        fh.write(text)
    print(text)


if __name__ == "__main__":
    main()
